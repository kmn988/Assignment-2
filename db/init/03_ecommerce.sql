-- ============================================================
-- VERIFY DATA
-- ============================================================

SELECT
    c.customer_name,
    o.order_id,
    o.order_status,
    o.fulfilment_store_id,
    oi.product_id,
    oi.quantity,
    r.reservation_id,
    r.store_id,
    r.reservation_status,
    r.released_at
FROM customer c
JOIN online_order o
    ON c.customer_id = o.customer_id
JOIN order_item oi
    ON o.order_id = oi.order_id
LEFT JOIN reservation r
    ON o.order_id = r.order_id
    AND oi.product_id = r.product_id
ORDER BY o.order_id;