-- ============================================================
-- E-COMMERCE SOURCE DATABASE
-- ============================================================
-- Tables:
--   CUSTOMER
--   ONLINE_ORDER
--   ORDER_ITEM
--   RESERVATION
--
-- product_id and store_id refer to records owned by the
-- Inventory database, so cross-database foreign keys are not
-- enforced here.
-- ============================================================


-- ============================================================
-- CUSTOMER
-- ============================================================

CREATE TABLE IF NOT EXISTS customer (
    customer_id     INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_name   VARCHAR(100) NOT NULL,
    email           VARCHAR(150) NOT NULL UNIQUE
);


-- ============================================================
-- ONLINE ORDER
-- ============================================================

CREATE TABLE IF NOT EXISTS online_order (
    order_id                INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id             INT NOT NULL REFERENCES customer(customer_id),
    fulfilment_store_id     INT NOT NULL,
    order_status            VARCHAR(30) NOT NULL
        CHECK (order_status IN ('PENDING', 'CONFIRMED', 'COMPLETED', 'CANCELLED')),
    order_total             NUMERIC(10,2) NOT NULL
        CHECK (order_total >= 0),
    created_at              TIMESTAMP NOT NULL DEFAULT now(),
    updated_at              TIMESTAMP NOT NULL DEFAULT now()
);


-- ============================================================
-- ORDER ITEM
-- ============================================================

CREATE TABLE IF NOT EXISTS order_item (
    order_item_id   INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id        INT NOT NULL REFERENCES online_order(order_id),
    product_id      INT NOT NULL,
    quantity        INT NOT NULL CHECK (quantity > 0),
    unit_price      NUMERIC(10,2) NOT NULL CHECK (unit_price >= 0),
    line_amount     NUMERIC(10,2) NOT NULL CHECK (line_amount >= 0)
);


-- ============================================================
-- RESERVATION
-- ============================================================

CREATE TABLE IF NOT EXISTS reservation (
    reservation_id      INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id            INT NOT NULL REFERENCES online_order(order_id),
    product_id          INT NOT NULL,
    store_id            INT NOT NULL,
    quantity            INT NOT NULL CHECK (quantity > 0),
    reservation_status  VARCHAR(30) NOT NULL
        CHECK (reservation_status IN ('ACTIVE', 'CANCELLED', 'EXPIRED', 'RELEASED')),
    created_at          TIMESTAMP NOT NULL DEFAULT now(),
    expires_at          TIMESTAMP NULL,
    released_at         TIMESTAMP NULL
);


